// pythonToken builds a token the way Python az does: base64(json.dumps(...)).
func pythonToken(link any, offset int) string {
	l := "null"
	if s, ok := link.(string); ok {
		l = strconv.Quote(s) // json.dumps output for plain ASCII URLs
	}
	return base64.StdEncoding.EncodeToString([]byte(fmt.Sprintf(`{"next_link": %s, "offset": %d}`, l, offset)))
}

func TestPageTokenMatchesPython(t *testing.T) {
	link := "https://management.azure.com/providers/Microsoft.Support/supportTickets?api-version=2024-04-01&$skiptoken=a%3D<b>"
	// Generated by Python: base64.b64encode(json.dumps({...}).encode()).
	const py = "eyJuZXh0X2xpbmsiOiAiaHR0cHM6Ly9tYW5hZ2VtZW50LmF6dXJlLmNvbS9wcm92aWRlcnMvTWljcm9zb2Z0LlN1cHBvcnQvc3VwcG9ydFRpY2tldHM/YXBpLXZlcnNpb249MjAyNC0wNC0wMSYkc2tpcHRva2VuPWElM0Q8Yj4iLCAib2Zmc2V0IjogM30="
	require.Equal(t, py, pythonToken(link, 3))
	require.Equal(t, py, pageToken{NextLink: link, Offset: 3}.encode())
	tok, err := decodeToken(py)
	require.NoError(t, err)
	require.Equal(t, pageToken{NextLink: link, Offset: 3}, *tok)

	require.Equal(t, "eyJuZXh0X2xpbmsiOiBudWxsLCAib2Zmc2V0IjogMn0=", pageToken{Offset: 2}.encode())
	tok, err = decodeToken(pythonToken(nil, 2))
	require.NoError(t, err)
	require.Equal(t, pageToken{Offset: 2}, *tok)
}

func TestDecodeTokenErrors(t *testing.T) {
	b64 := func(s string) string { return base64.StdEncoding.EncodeToString([]byte(s)) }
	for in, want := range map[string]string{
		"not base64!":              "Invalid Base64 string.",
		b64("\xff\xfe"):            "Error decoding UTF-8.",
		b64("{"):                   "Invalid JSON object.",
		b64("[1]"):                 "Decoded object is not a dictionary.",
		b64(`{"next_link": null}`): "`next_link` or `offset` doesn't exist.",
		b64(`{"offset": 1}`):       "`next_link` or `offset` doesn't exist.",
	} {
		_, err := decodeToken(in)
		require.EqualError(t, err, want, in)
	}
}

func TestCheckLink(t *testing.T) {
	ep := "https://management.azure.com"
	require.NoError(t, checkLink("https://management.azure.com/providers/x?api-version=1", ep))
	require.NoError(t, checkLink("https://management.azure.com:443/providers/x?api-version=1", ep))
	require.NoError(t, checkLink("https://management.azure.com/providers/x/?api-version=1", ep))
	for _, l := range []string{
		"http://management.azure.com/providers/x",
		"https://management.azure.com.attacker/providers/x",
		"https://evil.example/providers/x",
		"https://management.azure.com//evil.example/leak",
		"https://management.azure.com/a/../b",
		"https://user@management.azure.com/x",
		"https://management.azure.com\\@evil.example/x",
		"https://MANAGEMENT.azure.com/x",
		"https://management.azure.com:8443/x",
		"https://management.azure.com/a//b",
	} {
		require.EqualError(t, checkLink(l, ep), "`next_link` '"+l+"' is not a valid endpoint.", l)
	}
}

// pagedServer serves tickets in pages of sizes; ?page=N selects page N (default 1).
type pagedServer struct {
	mu    sync.Mutex
	pages []int // page sizes
	hits  []int // page numbers requested
	base  string
}

func (s *pagedServer) link(n int) string {
	return fmt.Sprintf("%s/subscriptions/sub1/providers/Microsoft.Support/supportTickets?api-version=2024-04-01&page=%d", s.base, n)
}

func (s *pagedServer) handle(w http.ResponseWriter, r *http.Request) {
	n := 1
	if p := r.URL.Query().Get("page"); p != "" {
		n, _ = strconv.Atoi(p)
	}
	s.mu.Lock()
	s.hits = append(s.hits, n)
	s.mu.Unlock()
	var items []map[string]string
	first := 0
	for _, size := range s.pages[:n-1] {
		first += size
	}
	for i := 0; i < s.pages[n-1]; i++ {
		items = append(items, map[string]string{"name": fmt.Sprintf("t%d", first+i+1)})
	}
	body := map[string]any{"value": items}
	if n < len(s.pages) {
		body["nextLink"] = s.link(n + 1)
	}
	json.NewEncoder(w).Encode(body)
}

func newPagedClient(t *testing.T, sizes ...int) (Client, *pagedServer) {
	s := &pagedServer{pages: sizes}
	c := newTestClient(t, Scope{SubscriptionID: "sub1"}, s.handle)
	s.base = c.(*subscriptionClient).arm.Endpoint()
	return c, s
}

func names(t *testing.T, c Client, max int, tok *pageToken) ([]string, *pageToken) {
	t.Helper()
	items, next, err := c.ListTickets(context.Background(), "", max, tok)
	require.NoError(t, err)
	var out []string
	for _, i := range items {
		out = append(out, *i.Name)
	}
	return out, next
}

func TestListPaging(t *testing.T) {
	c, s := newPagedClient(t, 3, 3, 2)

	got, next := names(t, c, 0, nil)
	require.Equal(t, []string{"t1", "t2", "t3", "t4", "t5", "t6", "t7", "t8"}, got)
	require.Nil(t, next)

	// Cut in the first page: Python's token has a null next_link.
	got, next = names(t, c, 2, nil)
	require.Equal(t, []string{"t1", "t2"}, got)
	require.Equal(t, &pageToken{Offset: 2}, next)

	// Cut mid-way through page 2.
	got, next = names(t, c, 4, nil)
	require.Equal(t, []string{"t1", "t2", "t3", "t4"}, got)
	require.Equal(t, &pageToken{NextLink: s.link(2), Offset: 1}, next)

	// Exact page boundary: token for the next page, which is not fetched.
	s.hits = nil
	got, next = names(t, c, 3, nil)
	require.Equal(t, []string{"t1", "t2", "t3"}, got)
	require.Equal(t, &pageToken{NextLink: s.link(2)}, next)
	require.Equal(t, []int{1}, s.hits)

	// Exact end of the last page: no token.
	_, next = names(t, c, 8, nil)
	require.Nil(t, next)

	// Resume from a page link, skipping offset.
	s.hits = nil
	got, next = names(t, c, 3, &pageToken{NextLink: s.link(2), Offset: 1})
	require.Equal(t, []string{"t5", "t6", "t7"}, got)
	require.Equal(t, &pageToken{NextLink: s.link(3), Offset: 1}, next)
	require.Equal(t, []int{2, 3}, s.hits)

	// Resume and cut again on the same page: offset counts from the page start.
	got, next = names(t, c, 1, &pageToken{NextLink: s.link(2), Offset: 1})
	require.Equal(t, []string{"t5"}, got)
	require.Equal(t, &pageToken{NextLink: s.link(2), Offset: 2}, next)

	// Resume a first-page token.
	got, next = names(t, c, 2, &pageToken{Offset: 2})
	require.Equal(t, []string{"t3", "t4"}, got)
	require.Equal(t, &pageToken{NextLink: s.link(2), Offset: 1}, next)

	// Resume to the end.
	got, next = names(t, c, 10, &pageToken{NextLink: s.link(3), Offset: 1})
	require.Equal(t, []string{"t8"}, got)
	require.Nil(t, next)

	// Without max the token is ignored, as in Python.
	got, _ = names(t, c, 0, &pageToken{NextLink: s.link(3), Offset: 1})
	require.Len(t, got, 8)
}

func TestListRejectsUntrustedLinkWithoutRequest(t *testing.T) {
	c, s := newPagedClient(t, 1)
	for _, l := range []string{"https://evil.example/x", s.base + ".attacker/x", "http" + s.base[len("https"):] + "/x"} {
		_, _, err := c.ListTickets(context.Background(), "", 5, &pageToken{NextLink: l})
		require.EqualError(t, err, "`next_link` '"+l+"' is not a valid endpoint.")
	}
	require.Empty(t, s.hits)
}

// runCmdStderr runs `az support <args>` against fake and returns stdout and stderr.
func runCmdStderr(t *testing.T, fake *fakeClient, args ...string) (string, string, error) {
	t.Helper()
	old := commandClientFn
	commandClientFn = func(*cobra.Command, bool) (Client, string, error) { return fake, "sub1", nil }
	t.Cleanup(func() { commandClientFn = old })
	cmd := NewSupportCommand()
	var out, errb bytes.Buffer
	cmd.SetOut(&out)
	cmd.SetErr(&errb)
	cmd.SetArgs(args)
	err := cmd.Execute()
	return out.String(), errb.String(), err
}

func TestListCommandsNextToken(t *testing.T) {
	f := newFake()
	f.files["ws"] = []*armsupport.FileDetails{{Name: ptr("a")}, {Name: ptr("b")}}
	f.nextToken = &pageToken{NextLink: "https://management.azure.com/x", Offset: 1}
	out, stderr, err := runCmdStderr(t, f, "no-subscription", "file", "list", "--file-workspace-name", "ws", "--max-items", "1",
		"--next-token", pythonToken("https://management.azure.com/y", 4))
	require.NoError(t, err)
	var got []any
	require.NoError(t, json.Unmarshal([]byte(out), &got))
	require.Len(t, got, 1)
	require.Equal(t, "WARNING: Token of next page: "+f.nextToken.encode()+"\n", stderr)
	require.Equal(t, &pageToken{NextLink: "https://management.azure.com/y", Offset: 4}, f.gotToken)

	f.calls = nil
	_, _, err = runCmdStderr(t, f, "in-subscription", "tickets", "list", "--next-token", "!!")
	require.EqualError(t, err, "--next-token: Invalid Base64 string.")
	require.Empty(t, f.calls)
}

func TestPageTokenNonASCIIMatchesPython(t *testing.T) {
	// base64.b64encode(json.dumps({"next_link": "https://management.azure.com/é😀", "offset": 3}).encode())
	const py = "eyJuZXh0X2xpbmsiOiAiaHR0cHM6Ly9tYW5hZ2VtZW50LmF6dXJlLmNvbS9cdTAwZTlcdWQ4M2RcdWRlMDAiLCAib2Zmc2V0IjogM30="
	tok := pageToken{NextLink: "https://management.azure.com/é😀", Offset: 3}
	require.Equal(t, py, tok.encode())
	got, err := decodeToken(py)
	require.NoError(t, err)
	require.Equal(t, &tok, got)
}

func TestEveryListCommandPassesNextToken(t *testing.T) {
	two := func() *fakeClient {
		f := newFake()
		f.tickets["t1"] = armsupport.TicketDetails{Name: ptr("t1")}
		f.tickets["t2"] = armsupport.TicketDetails{Name: ptr("t2")}
		f.comms["t1"] = []*armsupport.CommunicationDetails{{Name: ptr("a")}, {Name: ptr("b")}}
		f.chats["t1"] = []*armsupport.ChatTranscriptDetails{{Name: ptr("a")}, {Name: ptr("b")}}
		f.files["ws"] = []*armsupport.FileDetails{{Name: ptr("a")}, {Name: ptr("b")}}
		f.nextToken = &pageToken{NextLink: "https://management.azure.com/next", Offset: 1}
		return f
	}
	in := pythonToken("https://management.azure.com/in", 2)
	for _, scope := range []string{"in-subscription", "no-subscription"} {
		for _, args := range [][]string{
			{"tickets", "list"},
			{"communication", "list", "--ticket-name", "t1"},
			{"chat-transcript", "list", "--ticket-name", "t1"},
			{"file", "list", "--file-workspace-name", "ws"},
		} {
			name := scope + " " + strings.Join(args, " ")
			f := two()
			argv := append(append([]string{scope}, args...), "--max-items", "1", "--next-token", in)
			out, stderr, err := runCmdStderr(t, f, argv...)
			require.NoError(t, err, name)
			var got []any
			require.NoError(t, json.Unmarshal([]byte(out), &got), name)
			require.Len(t, got, 1, name)
			require.Equal(t, &pageToken{NextLink: "https://management.azure.com/in", Offset: 2}, f.gotToken, name)
			require.Equal(t, "WARNING: Token of next page: "+f.nextToken.encode()+"\n", stderr, name)
		}
	}
}
